ItemList.ById = {}
for _, item in ipairs(DefaultItems) do
    ItemList.ById[item.Id] = item
end

function ItemList.GetImage(itemId)
    local entry = ItemList.ById[itemId]
    return (entry and entry.Image ~= "") and entry.Image or nil
end

function ItemList.GetName(itemId)
    local entry = ItemList.ById[itemId]
    return entry and entry.Name or itemId
end

function ItemList.Build(BedwarsData)
    local result = {}
    local seenIds = {}
    local seenNames = {}

    for _, item in ipairs(DefaultItems) do
        seenIds[item.Id] = true
        seenNames[item.Name:lower()] = true
        table.insert(result, item)
    end

    -- Hỗ trợ cả cấu trúc BedwarsData.match.ItemMeta (từ bedwars-data.json) lẫn BedwarsData.ItemMeta
    local itemMeta = type(BedwarsData) == "table" and ((type(BedwarsData.match) == "table" and BedwarsData.match.ItemMeta) or BedwarsData.ItemMeta) or nil
    if type(itemMeta) == "table" then
        for itemId, meta in pairs(itemMeta) do
            if type(itemId) == "string" and not seenIds[itemId] and type(meta) == "table" then
                local displayName = type(meta.displayName) == "string" and meta.displayName:match("^%s*(.-)%s*$") or ""
                if displayName ~= "" then
                    if seenNames[displayName:lower()] then
                        displayName = displayName .. " (" .. itemId .. ")"
                    end
                    seenIds[itemId] = true
                    seenNames[displayName:lower()] = true
                    local img = type(meta.image) == "string" and meta.image or ""
                    local entry = { Id = itemId, Name = displayName, Image = img }
                    ItemList.ById[itemId] = entry
                    table.insert(result, entry)
                end
            end
        end
    end

    table.sort(result, function(a, b)
        return a.Name:lower() < b.Name:lower()
    end)

    return result
end

return ItemList
